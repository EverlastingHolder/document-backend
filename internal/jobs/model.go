// Package jobs defines the durable job model and repository boundary used by
// the asynchronous intake flow.
package jobs

import (
	"context"
	"errors"
	"time"
)

var (
	ErrNotFound              = errors.New("job not found")
	ErrConflict              = errors.New("idempotency conflict")
	ErrUnavailable           = errors.New("job storage unavailable")
	ErrInvalidSubmission     = errors.New("invalid job submission")
	ErrInvalidDelivery       = errors.New("invalid OCR delivery")
	ErrInvalidTransition     = errors.New("invalid job transition")
	ErrConflictingCompletion = errors.New("conflicting OCR completion")
	ErrResultGone            = errors.New("job result no longer retained")
)

type Status string

const (
	StatusQueued     Status = "queued"
	StatusProcessing Status = "processing"
	StatusCompleted  Status = "completed"
	StatusFailed     Status = "failed"
)

type Outcome uint8

const (
	OutcomeCreated Outcome = iota + 1
	OutcomeReplay
	OutcomeConflict
)

// Job is the durable, owner-scoped representation needed by the API. It does
// not contain image bytes, filesystem paths, OCR internals, or credentials.
type Job struct {
	ID             string
	OwnerID        string
	IdempotencyKey string
	RequestDigest  [32]byte
	ImageKey       string
	MediaType      string
	Size           int64
	Status         Status
	CreatedAt      time.Time
	UpdatedAt      time.Time
}

// Submission supplies identifiers generated by the application so the image
// object and its job/outbox rows can be correlated without exposing paths.
type Submission struct {
	JobID          string
	EventID        string
	OwnerID        string
	IdempotencyKey string
	RequestDigest  [32]byte
	ImageKey       string
	ImageSHA256    string
	MediaType      string
	Size           int64
}

type Accepted struct {
	JobID     string
	Status    Status
	CreatedAt time.Time
}

// Repository persists job state and the matching outbox event atomically.
// CreateQueued reports only a confirmed transaction outcome; errors may mean
// that the commit result is unknown and callers must retain the uploaded file.
type Repository interface {
	Lookup(ctx context.Context, ownerID, idempotencyKey string) (Job, error)
	CreateQueued(ctx context.Context, submission Submission) (Job, Outcome, error)
}

// StatusRecord is the minimal owner-scoped database projection needed to
// render one public job status. It deliberately excludes owner, idempotency,
// digest, and image metadata.
type StatusRecord struct {
	ID              string
	Status          Status
	CreatedAt       time.Time
	UpdatedAt       time.Time
	StartedAt       *time.Time
	FinishedAt      *time.Time
	ResultJSON      []byte
	PipelineVersion *string
	ErrorCode       *string
	ResultPurged    bool
}

// StatusRepository reads one job only when its authenticated owner matches.
// Implementations return ErrNotFound for both absent and non-owned IDs.
type StatusRepository interface {
	GetOwnedStatus(ctx context.Context, ownerID, jobID string) (StatusRecord, error)
}

type ReceiptOutcome uint8

const (
	ReceiptReceived ReceiptOutcome = iota + 1
	ReceiptAlreadyPurged
	ReceiptActive
)

// ReceiptRepository records an explicit client receipt before terminal data
// is purged. It must apply owner filtering and make repeated receipts safe.
type ReceiptRepository interface {
	AcknowledgeOwnedResult(ctx context.Context, ownerID, jobID string) (ReceiptOutcome, error)
}

type MaintenanceSnapshot struct {
	QueuedJobs             int64
	OldestQueuedAge        time.Duration
	ExpiredLeases          int64
	TerminalImagesPending  int64
	TerminalResultsPending int64
}

type MaintenanceRepository interface {
	ReadMaintenanceSnapshot(ctx context.Context) (MaintenanceSnapshot, error)
}

// Envelope is the privacy-minimal RabbitMQ message. Image bytes, paths, OCR
// output, and owner data never belong in this message.
type Envelope struct {
	SchemaVersion int    `json:"schema_version"`
	EventID       string `json:"event_id"`
	JobID         string `json:"job_id"`
	AttemptNo     int    `json:"attempt_no"`
}

type DeliveryDecision string

const (
	DecisionExecute DeliveryDecision = "execute"
	DecisionWait    DeliveryDecision = "wait"
	DecisionAck     DeliveryDecision = "ack"
)

type Execution struct {
	AttemptToken            string    `json:"attempt_token"`
	ImageKey                string    `json:"image_key"`
	MediaType               string    `json:"media_type"`
	Size                    int64     `json:"size_bytes"`
	AttemptNo               int       `json:"attempt_no"`
	StartedAt               time.Time `json:"-"`
	DeadlineAt              time.Time `json:"deadline_at"`
	LeaseExpiresAt          time.Time `json:"lease_expires_at"`
	PipelineVersion         string    `json:"pipeline_version"`
	HardProcessingTimeoutMS int64     `json:"hard_processing_timeout_ms"`
	CompletionBudgetMS      int64     `json:"completion_budget_ms"`
}

type ClaimResult struct {
	Decision     DeliveryDecision `json:"decision"`
	Execution    *Execution       `json:"execution,omitempty"`
	RetryAfter   time.Duration    `json:"-"`
	RetryAfterMS int64            `json:"retry_after_ms,omitempty"`
}

type LeasedOutbox struct {
	Envelope            Envelope
	EventType           string
	StoredSchemaVersion string
	ClaimToken          string
	ClaimUntil          time.Time
}

type Completion struct {
	Envelope
	AttemptToken string             `json:"attempt_token"`
	Fields       map[string]*string `json:"fields"`
}

type PersistedCompletion struct {
	Envelope        Envelope
	AttemptToken    string
	PipelineVersion string
	CanonicalJSON   []byte
}

type Failure struct {
	Envelope
	AttemptToken string `json:"attempt_token"`
	ErrorCode    string `json:"error_code"`
}

type Rejection struct {
	Envelope
}

type RetryPolicy struct {
	MaxAttempts    int
	InitialBackoff time.Duration
	MaxBackoff     time.Duration
}

// ExecutionRepository contains the database-owned state transitions used by
// the private OCR consumer and outbox relay. Implementations must commit state
// before returning an ACK decision.
type ExecutionRepository interface {
	LeaseOutbox(ctx context.Context, limit int, leaseFor time.Duration) ([]LeasedOutbox, error)
	MarkOutboxPublished(ctx context.Context, eventID, claimToken string) error
	ReleaseOutbox(ctx context.Context, eventID, claimToken, safeErrorCode string, retryAfter time.Duration) error
	ClaimDelivery(ctx context.Context, envelope Envelope, leaseFor time.Duration, policy RetryPolicy) (ClaimResult, error)
	PersistCompletion(ctx context.Context, completion PersistedCompletion, policy RetryPolicy) (DeliveryDecision, error)
	FailAttempt(ctx context.Context, failure Failure, policy RetryPolicy) (DeliveryDecision, error)
	RejectDelivery(ctx context.Context, rejection Rejection) (DeliveryDecision, error)
	RecoverExpired(ctx context.Context, limit int, policy RetryPolicy) (int, error)
}
